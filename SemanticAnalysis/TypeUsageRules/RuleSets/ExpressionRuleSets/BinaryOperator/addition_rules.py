from Tokenization.symbols import *
from SemanticAnalysis.TypeUsageRules.utils import make_key


VALID_ADD_OPERATIONS_STRING = {
    make_key(STRING, UNDERSCORE, PLUS, UNDERSCORE, STRING) : STRING,
    make_key(CHAR, UNDERSCORE, PLUS, UNDERSCORE, STRING): STRING,
    make_key(STRING, UNDERSCORE, PLUS, UNDERSCORE, CHAR): STRING,
    make_key(CHAR, UNDERSCORE, PLUS, UNDERSCORE, CHAR): STRING,
}

VALID_ADD_OPERATIONS_INT = {
    make_key(INT, UNDERSCORE, PLUS, UNDERSCORE, INT): INT
}

VALID_ADD_OPERATIONS_LONG = {
    make_key(INT, UNDERSCORE, PLUS, UNDERSCORE, LONG): LONG,
    make_key(LONG, UNDERSCORE, PLUS, UNDERSCORE, INT): LONG,
    make_key(LONG, UNDERSCORE, PLUS, UNDERSCORE, LONG): LONG,
}

VALID_ADD_OPERATIONS_FLOAT = {
    make_key(FLOAT, UNDERSCORE, PLUS, UNDERSCORE, FLOAT): FLOAT,
    make_key(INT, UNDERSCORE, PLUS, UNDERSCORE, FLOAT): FLOAT,
    make_key(FLOAT, UNDERSCORE, PLUS, UNDERSCORE, INT): FLOAT,
}

VALID_ADD_OPERATIONS_DOUBLE = {
    make_key(DOUBLE, UNDERSCORE, PLUS, UNDERSCORE, DOUBLE): DOUBLE,
    make_key(FLOAT, UNDERSCORE, PLUS, UNDERSCORE, DOUBLE): DOUBLE,
    make_key(DOUBLE, UNDERSCORE, PLUS, UNDERSCORE, FLOAT): DOUBLE,
    make_key(INT, UNDERSCORE, PLUS, UNDERSCORE, DOUBLE): DOUBLE,
    make_key(DOUBLE, UNDERSCORE, PLUS, UNDERSCORE, INT): DOUBLE,
    make_key(LONG, UNDERSCORE, PLUS, UNDERSCORE, DOUBLE): DOUBLE,
    make_key(DOUBLE, UNDERSCORE, PLUS, UNDERSCORE, LONG): DOUBLE,
    make_key(LONG, UNDERSCORE, PLUS, UNDERSCORE, FLOAT): DOUBLE,
    make_key(FLOAT, UNDERSCORE, PLUS, UNDERSCORE, LONG): DOUBLE,
}


def make_addition_rule_table() -> dict:
    addition_rule_table = dict()
    addition_rule_table.update(VALID_ADD_OPERATIONS_STRING)
    addition_rule_table.update(VALID_ADD_OPERATIONS_INT)
    addition_rule_table.update(VALID_ADD_OPERATIONS_LONG)
    addition_rule_table.update(VALID_ADD_OPERATIONS_FLOAT)
    addition_rule_table.update(VALID_ADD_OPERATIONS_DOUBLE)
    return addition_rule_table
