from Tokenization.symbols import *
from SemanticAnalysis.TypeUsageRules.utils import make_key


VALID_NOT_EQ_OPERATIONS_STRING = {
    make_key(STRING, UNDERSCORE, BANG_EQUAL, UNDERSCORE, STRING) : BOOL,
    make_key(CHAR, UNDERSCORE, BANG_EQUAL, UNDERSCORE, CHAR): BOOL,
}

VALID_NOT_EQ_OPERATIONS_INT = {
    make_key(INT, UNDERSCORE, BANG_EQUAL, UNDERSCORE, INT): BOOL
}

VALID_NOT_EQ_OPERATIONS_LONG = {
    make_key(INT, UNDERSCORE, BANG_EQUAL, UNDERSCORE, LONG): BOOL,
    make_key(LONG, UNDERSCORE, BANG_EQUAL, UNDERSCORE, INT): BOOL,
    make_key(LONG, UNDERSCORE, BANG_EQUAL, UNDERSCORE, LONG): BOOL,
}

VALID_NOT_EQ_OPERATIONS_FLOAT = {
    make_key(FLOAT, UNDERSCORE, BANG_EQUAL, UNDERSCORE, FLOAT): BOOL,
    make_key(INT, UNDERSCORE, BANG_EQUAL, UNDERSCORE, FLOAT): BOOL,
    make_key(FLOAT, UNDERSCORE, BANG_EQUAL, UNDERSCORE, INT): BOOL,
}

VALID_NOT_EQ_OPERATIONS_DOUBLE = {
    make_key(DOUBLE, UNDERSCORE, BANG_EQUAL, UNDERSCORE, DOUBLE): BOOL,
    make_key(FLOAT, UNDERSCORE, BANG_EQUAL, UNDERSCORE, DOUBLE): BOOL,
    make_key(DOUBLE, UNDERSCORE, BANG_EQUAL, UNDERSCORE, FLOAT): BOOL,
    make_key(INT, UNDERSCORE, BANG_EQUAL, UNDERSCORE, DOUBLE): BOOL,
    make_key(DOUBLE, UNDERSCORE, BANG_EQUAL, UNDERSCORE, INT): BOOL,
    make_key(LONG, UNDERSCORE, BANG_EQUAL, UNDERSCORE, DOUBLE): BOOL,
    make_key(DOUBLE, UNDERSCORE, BANG_EQUAL, UNDERSCORE, LONG): BOOL,
    make_key(LONG, UNDERSCORE, BANG_EQUAL, UNDERSCORE, FLOAT): BOOL,
    make_key(FLOAT, UNDERSCORE, BANG_EQUAL, UNDERSCORE, LONG): BOOL,
}


def make_not_equal_rule_table() -> dict:
    not_equal_rule_table = dict()
    not_equal_rule_table.update(VALID_NOT_EQ_OPERATIONS_STRING)
    not_equal_rule_table.update(VALID_NOT_EQ_OPERATIONS_INT)
    not_equal_rule_table.update(VALID_NOT_EQ_OPERATIONS_LONG)
    not_equal_rule_table.update(VALID_NOT_EQ_OPERATIONS_FLOAT)
    not_equal_rule_table.update(VALID_NOT_EQ_OPERATIONS_DOUBLE)
    return not_equal_rule_table