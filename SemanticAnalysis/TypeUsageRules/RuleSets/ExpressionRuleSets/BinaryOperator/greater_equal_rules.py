from Tokenization.symbols import *
from SemanticAnalysis.TypeUsageRules.utils import make_key


VALID_GREATER_EQUAL_OPERATIONS_STRING = {
    make_key(STRING, UNDERSCORE, EQUAL_EQUAL, UNDERSCORE, STRING) : BOOL,
    make_key(CHAR, UNDERSCORE, EQUAL_EQUAL, UNDERSCORE, CHAR): BOOL,
}

VALID_GREATER_EQUAL_OPERATIONS_INT = {
    make_key(INT, UNDERSCORE, EQUAL_EQUAL, UNDERSCORE, INT): BOOL
}

VALID_GREATER_EQUAL_OPERATIONS_LONG = {
    make_key(INT, UNDERSCORE, EQUAL_EQUAL, UNDERSCORE, LONG): BOOL,
    make_key(LONG, UNDERSCORE, EQUAL_EQUAL, UNDERSCORE, INT): BOOL,
    make_key(LONG, UNDERSCORE, EQUAL_EQUAL, UNDERSCORE, LONG): BOOL,
}

VALID_GREATER_EQUAL_OPERATIONS_FLOAT = {
    make_key(FLOAT, UNDERSCORE, EQUAL_EQUAL, UNDERSCORE, FLOAT): BOOL,
    make_key(INT, UNDERSCORE, EQUAL_EQUAL, UNDERSCORE, FLOAT): BOOL,
    make_key(FLOAT, UNDERSCORE, EQUAL_EQUAL, UNDERSCORE, INT): BOOL,
}

VALID_GREATER_EQUAL_OPERATIONS_DOUBLE = {
    make_key(DOUBLE, UNDERSCORE, EQUAL_EQUAL, UNDERSCORE, DOUBLE): BOOL,
    make_key(FLOAT, UNDERSCORE, EQUAL_EQUAL, UNDERSCORE, DOUBLE): BOOL,
    make_key(DOUBLE, UNDERSCORE, EQUAL_EQUAL, UNDERSCORE, FLOAT): BOOL,
    make_key(INT, UNDERSCORE, EQUAL_EQUAL, UNDERSCORE, DOUBLE): BOOL,
    make_key(DOUBLE, UNDERSCORE, EQUAL_EQUAL, UNDERSCORE, INT): BOOL,
    make_key(LONG, UNDERSCORE, EQUAL_EQUAL, UNDERSCORE, DOUBLE): BOOL,
    make_key(DOUBLE, UNDERSCORE, EQUAL_EQUAL, UNDERSCORE, LONG): BOOL,
    make_key(LONG, UNDERSCORE, EQUAL_EQUAL, UNDERSCORE, FLOAT): BOOL,
    make_key(FLOAT, UNDERSCORE, EQUAL_EQUAL, UNDERSCORE, LONG): BOOL,
}


def make_greater_equal_rule_table() -> dict:
    greater_equal_rule_table = dict()
    greater_equal_rule_table.update(VALID_GREATER_EQUAL_OPERATIONS_STRING)
    greater_equal_rule_table.update(VALID_GREATER_EQUAL_OPERATIONS_INT)
    greater_equal_rule_table.update(VALID_GREATER_EQUAL_OPERATIONS_LONG)
    greater_equal_rule_table.update(VALID_GREATER_EQUAL_OPERATIONS_FLOAT)
    greater_equal_rule_table.update(VALID_GREATER_EQUAL_OPERATIONS_DOUBLE)
    return greater_equal_rule_table