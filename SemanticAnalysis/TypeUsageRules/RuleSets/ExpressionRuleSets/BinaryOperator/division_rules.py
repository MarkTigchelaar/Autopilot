from Tokenization.symbols import *
from SemanticAnalysis.TypeUsageRules.utils import make_key


VALID_DIVISION_OPERATIONS_INT = {
    make_key(INT, UNDERSCORE, SLASH, UNDERSCORE, INT): INT
}

VALID_DIVISION_OPERATIONS_LONG = {
    make_key(INT, UNDERSCORE, SLASH, UNDERSCORE, LONG): LONG,
    make_key(LONG, UNDERSCORE, SLASH, UNDERSCORE, INT): LONG,
    make_key(LONG, UNDERSCORE, SLASH, UNDERSCORE, LONG): LONG,
}

VALID_DIVISION_OPERATIONS_FLOAT = {
    make_key(FLOAT, UNDERSCORE, SLASH, UNDERSCORE, FLOAT): FLOAT,
    make_key(INT, UNDERSCORE, SLASH, UNDERSCORE, FLOAT): FLOAT,
    make_key(FLOAT, UNDERSCORE, SLASH, UNDERSCORE, INT): FLOAT,
}

VALID_DIVISION_OPERATIONS_DOUBLE = {
    make_key(DOUBLE, UNDERSCORE, SLASH, UNDERSCORE, DOUBLE): DOUBLE,
    make_key(FLOAT, UNDERSCORE, SLASH, UNDERSCORE, DOUBLE): DOUBLE,
    make_key(DOUBLE, UNDERSCORE, SLASH, UNDERSCORE, FLOAT): DOUBLE,
    make_key(INT, UNDERSCORE, SLASH, UNDERSCORE, DOUBLE): DOUBLE,
    make_key(DOUBLE, UNDERSCORE, SLASH, UNDERSCORE, INT): DOUBLE,
    make_key(LONG, UNDERSCORE, SLASH, UNDERSCORE, DOUBLE): DOUBLE,
    make_key(DOUBLE, UNDERSCORE, SLASH, UNDERSCORE, LONG): DOUBLE,
    make_key(LONG, UNDERSCORE, SLASH, UNDERSCORE, FLOAT): DOUBLE,
    make_key(FLOAT, UNDERSCORE, SLASH, UNDERSCORE, LONG): DOUBLE,
}


def make_division_rule_table() -> dict:
    division_rule_table = dict()
    division_rule_table.update(VALID_DIVISION_OPERATIONS_INT)
    division_rule_table.update(VALID_DIVISION_OPERATIONS_LONG)
    division_rule_table.update(VALID_DIVISION_OPERATIONS_FLOAT)
    division_rule_table.update(VALID_DIVISION_OPERATIONS_DOUBLE)
    return division_rule_table
