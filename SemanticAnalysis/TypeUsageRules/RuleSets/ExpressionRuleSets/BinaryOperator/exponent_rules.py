from Tokenization.symbols import *
from SemanticAnalysis.TypeUsageRules.utils import make_key



VALID_EXPONENT_OPERATIONS_INT = {
    make_key(INT, UNDERSCORE, CARROT, UNDERSCORE, INT): INT
}

VALID_EXPONENT_OPERATIONS_LONG = {
    make_key(INT, UNDERSCORE, CARROT, UNDERSCORE, LONG): LONG,
    make_key(LONG, UNDERSCORE, CARROT, UNDERSCORE, INT): LONG,
    make_key(LONG, UNDERSCORE, CARROT, UNDERSCORE, LONG): LONG,
}

VALID_EXPONENT_OPERATIONS_FLOAT = {
    make_key(FLOAT, UNDERSCORE, CARROT, UNDERSCORE, FLOAT): FLOAT,
    make_key(INT, UNDERSCORE, CARROT, UNDERSCORE, FLOAT): FLOAT,
    make_key(FLOAT, UNDERSCORE, CARROT, UNDERSCORE, INT): FLOAT,
}

VALID_EXPONENT_OPERATIONS_DOUBLE = {
    make_key(DOUBLE, UNDERSCORE, CARROT, UNDERSCORE, DOUBLE): DOUBLE,
    make_key(FLOAT, UNDERSCORE, CARROT, UNDERSCORE, DOUBLE): DOUBLE,
    make_key(DOUBLE, UNDERSCORE, CARROT, UNDERSCORE, FLOAT): DOUBLE,
    make_key(INT, UNDERSCORE, CARROT, UNDERSCORE, DOUBLE): DOUBLE,
    make_key(DOUBLE, UNDERSCORE, CARROT, UNDERSCORE, INT): DOUBLE,
    make_key(LONG, UNDERSCORE, CARROT, UNDERSCORE, DOUBLE): DOUBLE,
    make_key(DOUBLE, UNDERSCORE, CARROT, UNDERSCORE, LONG): DOUBLE,
    make_key(LONG, UNDERSCORE, CARROT, UNDERSCORE, FLOAT): DOUBLE,
    make_key(FLOAT, UNDERSCORE, CARROT, UNDERSCORE, LONG): DOUBLE,
}


def make_exponent_rule_table() -> dict:
    exponent_rule_table = dict()
    exponent_rule_table.update(VALID_EXPONENT_OPERATIONS_INT)
    exponent_rule_table.update(VALID_EXPONENT_OPERATIONS_LONG)
    exponent_rule_table.update(VALID_EXPONENT_OPERATIONS_FLOAT)
    exponent_rule_table.update(VALID_EXPONENT_OPERATIONS_DOUBLE)
    return exponent_rule_table
