from Tokenization.symbols import *
from SemanticAnalysis.TypeUsageRules.utils import make_key


VALID_MULTIPLY_OPERATIONS_STRING = {
    make_key(STRING, UNDERSCORE, STAR, UNDERSCORE, STRING) : STRING,
    make_key(CHAR, UNDERSCORE, STAR, UNDERSCORE, STRING): STRING,
    make_key(STRING, UNDERSCORE, STAR, UNDERSCORE, CHAR): STRING,
    make_key(CHAR, UNDERSCORE, STAR, UNDERSCORE, CHAR): STRING,
}

VALID_MULTIPLY_OPERATIONS_INT = {
    make_key(INT, UNDERSCORE, STAR, UNDERSCORE, INT): INT
}

VALID_MULTIPLY_OPERATIONS_LONG = {
    make_key(INT, UNDERSCORE, STAR, UNDERSCORE, LONG): LONG,
    make_key(LONG, UNDERSCORE, STAR, UNDERSCORE, INT): LONG,
    make_key(LONG, UNDERSCORE, STAR, UNDERSCORE, LONG): LONG,
}

VALID_MULTIPLY_OPERATIONS_FLOAT = {
    make_key(FLOAT, UNDERSCORE, STAR, UNDERSCORE, FLOAT): FLOAT,
    make_key(INT, UNDERSCORE, STAR, UNDERSCORE, FLOAT): FLOAT,
    make_key(FLOAT, UNDERSCORE, STAR, UNDERSCORE, INT): FLOAT,
}

VALID_MULTIPLY_OPERATIONS_DOUBLE = {
    make_key(DOUBLE, UNDERSCORE, STAR, UNDERSCORE, DOUBLE): DOUBLE,
    make_key(FLOAT, UNDERSCORE, STAR, UNDERSCORE, DOUBLE): DOUBLE,
    make_key(DOUBLE, UNDERSCORE, STAR, UNDERSCORE, FLOAT): DOUBLE,
    make_key(INT, UNDERSCORE, STAR, UNDERSCORE, DOUBLE): DOUBLE,
    make_key(DOUBLE, UNDERSCORE, STAR, UNDERSCORE, INT): DOUBLE,
    make_key(LONG, UNDERSCORE, STAR, UNDERSCORE, DOUBLE): DOUBLE,
    make_key(DOUBLE, UNDERSCORE, STAR, UNDERSCORE, LONG): DOUBLE,
    make_key(LONG, UNDERSCORE, STAR, UNDERSCORE, FLOAT): DOUBLE,
    make_key(FLOAT, UNDERSCORE, STAR, UNDERSCORE, LONG): DOUBLE,
}


def make_multiplication_rule_table() -> dict:
    multiplication_rule_table = dict()
    multiplication_rule_table.update(VALID_MULTIPLY_OPERATIONS_STRING)
    multiplication_rule_table.update(VALID_MULTIPLY_OPERATIONS_INT)
    multiplication_rule_table.update(VALID_MULTIPLY_OPERATIONS_LONG)
    multiplication_rule_table.update(VALID_MULTIPLY_OPERATIONS_FLOAT)
    multiplication_rule_table.update(VALID_MULTIPLY_OPERATIONS_DOUBLE)
    return multiplication_rule_table
