from Tokenization.symbols import *
from SemanticAnalysis.TypeUsageRules.utils import make_key



VALID_SUBTRACTION_OPERATIONS_INT = {
    make_key(INT, UNDERSCORE, MINUS, UNDERSCORE, INT): INT
}

VALID_SUBTRACTION_OPERATIONS_LONG = {
    make_key(INT, UNDERSCORE, MINUS, UNDERSCORE, LONG): LONG,
    make_key(LONG, UNDERSCORE, MINUS, UNDERSCORE, INT): LONG,
    make_key(LONG, UNDERSCORE, MINUS, UNDERSCORE, LONG): LONG,
}

VALID_SUBTRACTION_OPERATIONS_FLOAT = {
    make_key(FLOAT, UNDERSCORE, MINUS, UNDERSCORE, FLOAT): FLOAT,
    make_key(INT, UNDERSCORE, MINUS, UNDERSCORE, FLOAT): FLOAT,
    make_key(FLOAT, UNDERSCORE, MINUS, UNDERSCORE, INT): FLOAT,
}

VALID_SUBTRACTION_OPERATIONS_DOUBLE = {
    make_key(DOUBLE, UNDERSCORE, MINUS, UNDERSCORE, DOUBLE): DOUBLE,
    make_key(FLOAT, UNDERSCORE, MINUS, UNDERSCORE, DOUBLE): DOUBLE,
    make_key(DOUBLE, UNDERSCORE, MINUS, UNDERSCORE, FLOAT): DOUBLE,
    make_key(INT, UNDERSCORE, MINUS, UNDERSCORE, DOUBLE): DOUBLE,
    make_key(DOUBLE, UNDERSCORE, MINUS, UNDERSCORE, INT): DOUBLE,
    make_key(LONG, UNDERSCORE, MINUS, UNDERSCORE, DOUBLE): DOUBLE,
    make_key(DOUBLE, UNDERSCORE, MINUS, UNDERSCORE, LONG): DOUBLE,
    make_key(LONG, UNDERSCORE, MINUS, UNDERSCORE, FLOAT): DOUBLE,
    make_key(FLOAT, UNDERSCORE, MINUS, UNDERSCORE, LONG): DOUBLE,
}


def make_subtraction_rule_table() -> dict:
    subtraction_rule_table = dict()
    subtraction_rule_table.update(VALID_SUBTRACTION_OPERATIONS_INT)
    subtraction_rule_table.update(VALID_SUBTRACTION_OPERATIONS_LONG)
    subtraction_rule_table.update(VALID_SUBTRACTION_OPERATIONS_FLOAT)
    subtraction_rule_table.update(VALID_SUBTRACTION_OPERATIONS_DOUBLE)
    return subtraction_rule_table
